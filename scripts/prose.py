#!/usr/bin/env python3
"""Edit a world's prose as Markdown instead of JSON.

A world file is a runtime format: quoted strings, escaped newlines, structure
interleaved with writing. That is a bad surface for the part of a world that is
actually *written*. This moves every player-facing string into a Markdown file you
can edit like a manuscript, and puts it back afterwards.

    python scripts/prose.py extract worlds/wayfarer.json     # JSON -> .prose.md
    python scripts/prose.py apply   worlds/wayfarer.prose.md  # .prose.md -> JSON

The heading above each block is the address of that string inside the JSON. Edit
the text; leave the headings alone. `apply` validates the world before it writes,
so a broken edit fails loudly instead of shipping.

Names and aliases are deliberately absent: they decide what a player can *type*,
not what they read, and changing one can collide with another word in the room.
Those stay in the JSON, next to the linter that checks them.
"""

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from adventure.loader import WorldValidationError, load_world   # noqa: E402
from adventure.pronouns import unknown_tokens                   # noqa: E402

HEADING = re.compile(r"^###\s+`([^`]+)`")
VOICE_START = "<!-- voice:start -->"
VOICE_END = "<!-- voice:end -->"

PREAMBLE = """<!-- Generated by scripts/prose.py. Edit the prose, then:
       python scripts/prose.py apply {prose}
     Headings are addresses into {world} — leave them alone. -->

# {title} — prose

Every block below is one string the player reads. Edit them freely, including
into several paragraphs; blank lines survive the round trip.

Where the prose has to name the protagonist in the third person, write a pronoun
token rather than a word — `{they} {them} {their} {theirs} {themselves}`, with
`{s}` and `{are}`/`{were}`/`{have}`/`{do}` for the verbs that have to agree. The
player chooses which words those become. See docs/AUTHORING.md.

{voice_start}
## Voice

*Notes here are never overwritten by `extract`. Anything you write in this section
is the style reference for prose added later.*

{voice_end}
"""


# --- addressing --------------------------------------------------------------


def _step(node, key: str):
    """One segment of an address. `[2]` indexes a list; `[some_id]` finds the
    member of a list whose "id" field matches."""
    match = re.fullmatch(r"\[(.+)\]", key)
    if match is None:
        return node[key]
    inner = match.group(1)
    if inner.isdigit():
        return node[int(inner)]
    return next(item for item in node if item.get("id") == inner)


def _segments(address: str) -> list[str]:
    """'doors.window.listening[0].text' -> ['doors','window','listening','[0]','text']"""
    parts: list[str] = []
    for chunk in address.split("."):
        head, *brackets = re.split(r"(\[[^\]]+\])", chunk)
        if head:
            parts.append(head)
        parts.extend(b for b in brackets if b)
    return parts


def read_at(world: dict, address: str):
    node = world
    for key in _segments(address):
        node = _step(node, key)
    return node


def write_at(world: dict, address: str, value: str) -> None:
    *lead, last = _segments(address)
    node = world
    for key in lead:
        node = _step(node, key)
    if re.fullmatch(r"\[\d+\]", last):
        node[int(last[1:-1])] = value
    else:
        node[last] = value


# --- what counts as prose ----------------------------------------------------


def _room_name(world: dict, room_id: str) -> str:
    return world["rooms"].get(room_id, {}).get("name", room_id)


def _guard(world: dict, rule: dict) -> str:
    """A one-line English summary of when a rule fires, so an editor rewriting the
    third of six dialogue lines can see which one they are holding."""
    parts = []
    if rule.get("once"):
        parts.append("first time only")
    if rule.get("rooms"):
        parts.append("in " + " or ".join(_room_name(world, r) for r in rule["rooms"]))
    for flag, wanted in (rule.get("requires_flags") or {}).items():
        parts.append(f"when {flag} is {str(wanted).lower()}")
    for counter, bounds in (rule.get("requires_counters") or {}).items():
        if bounds.get("at_least") is not None:
            parts.append(f"when {counter} \u2265 {bounds['at_least']}")
        if bounds.get("at_most") is not None:
            parts.append(f"when {counter} \u2264 {bounds['at_most']}")
    for door, open_ in (rule.get("requires_doors") or {}).items():
        parts.append(f"when the {door} is {'open' if open_ else 'shut'}")
    return ", ".join(parts) if parts else "otherwise (the catch-all)"


def prose_blocks(world: dict) -> list[tuple[str, str, str, str]]:
    """Every player-facing string, as (section, address, note, text), in reading
    order. The note goes after the heading, where `apply` ignores it."""
    out: list[tuple[str, str, str, str]] = []

    def add(section: str, address: str, note: str = "") -> None:
        try:
            value = read_at(world, address)
        except (KeyError, IndexError, StopIteration):
            return
        if isinstance(value, str) and value:
            out.append((section, address, note, value))

    add("Opening", "intro", "printed once, before the first room")
    add("Opening", "win_epilogue", "fallback last words for a win")

    for room_id, room in world["rooms"].items():
        section = f"Room — {room['name']}"
        add(section, f"rooms.{room_id}.description", "what you see on arriving")
        add(section, f"rooms.{room_id}.alt_description",
            f"instead, once {room.get('alt_flag')} is set")
        add(section, f"rooms.{room_id}.sounds", "the answer to `listen`")
        add(section, f"rooms.{room_id}.alt_sounds",
            f"instead, once {room.get('alt_flag')} is set")
        for direction, exit_ in room.get("exits", {}).items():
            add(section, f"rooms.{room_id}.exits.{direction}.pass_message",
                f"going {direction}, to the {_room_name(world, exit_['to'])}")

    for door_id, door in world.get("doors", {}).items():
        section = f"Door — {door['name']}"
        add(section, f"doors.{door_id}.description", "on examining it")
        add(section, f"doors.{door_id}.locked_message", "when it will not open")
        add(section, f"doors.{door_id}.open_message", "when it opens")
        for index, rule in enumerate(door.get("listening", [])):
            add(section, f"doors.{door_id}.listening[{index}].text",
                "listening: " + _guard(world, rule))

    for item_id, item in world.get("items", {}).items():
        section = f"Item — {item['name']}"
        add(section, f"items.{item_id}.description", "on examining it")
        add(section, f"items.{item_id}.alt_description",
            f"instead, once {item.get('alt_flag')} is set")
        add(section, f"items.{item_id}.open_refusal", "on trying to open it")

    for npc_id, npc in world.get("npcs", {}).items():
        section = f"Character — {npc['name']}"
        add(section, f"npcs.{npc_id}.description", "on examining them")
        for index, rule in enumerate(npc.get("dialogue", [])):
            add(section, f"npcs.{npc_id}.dialogue[{index}].text",
                "talking: " + _guard(world, rule))

    for interaction in world.get("interactions", []):
        target = interaction.get("target_id")
        add("Interactions", f"interactions[{interaction['id']}].message",
            f"use {interaction['item_id']}" + (f" on {target}" if target else ""))

    for trigger in world.get("triggers", []):
        section = "Triggers"
        when = "on arriving" if trigger.get("when", "enter") == "enter" else "every turn"
        add(section, f"triggers[{trigger['id']}].text", f"{when}, {_guard(world, trigger)}")
        for index, effect in enumerate(trigger.get("effects", [])):
            add(section, f"triggers[{trigger['id']}].effects[{index}].epilogue",
                f"the last words of this {effect.get('outcome', 'ending')}")
            add(section, f"triggers[{trigger['id']}].effects[{index}].banner",
                "the closing line under it")
    return out


# --- the two directions ------------------------------------------------------


def extract(world_path: Path, prose_path: Path) -> None:
    world = json.loads(world_path.read_text(encoding="utf-8"))
    voice = _existing_voice(prose_path)
    lines = [PREAMBLE.format(title=world["title"], prose=prose_path, world=world_path,
                             voice_start=VOICE_START,
                             voice_end=VOICE_END).rstrip() if voice is None else voice]

    section = None
    for block_section, address, note, text in prose_blocks(world):
        if block_section != section:
            section = block_section
            lines.append(f"\n\n## {section}")
        suffix = f" — *{note}*" if note else ""
        lines.append(f"\n\n### `{address}`{suffix}\n\n{text}")
    prose_path.write_text("".join(lines) + "\n", encoding="utf-8")
    print(f"{prose_path}: {len(prose_blocks(world))} blocks from {world_path}")


def _existing_voice(prose_path: Path) -> str | None:
    """Keep everything up to the end of the Voice block. Notes the author wrote
    about how this world should sound must survive a regeneration."""
    if not prose_path.is_file():
        return None
    text = prose_path.read_text(encoding="utf-8")
    end = text.find(VOICE_END)
    return None if end == -1 else text[: end + len(VOICE_END)]


def parse_prose(prose_path: Path) -> dict[str, str]:
    blocks: dict[str, str] = {}
    address, buffer = None, []
    for line in prose_path.read_text(encoding="utf-8").splitlines():
        heading = HEADING.match(line)
        if heading is not None:
            if address is not None:
                blocks[address] = "\n".join(buffer).strip()
            address, buffer = heading.group(1), []
        elif address is not None:
            if line.startswith("#"):            # a section heading ends the block
                blocks[address] = "\n".join(buffer).strip()
                address, buffer = None, []
            else:
                buffer.append(line)
    if address is not None:
        blocks[address] = "\n".join(buffer).strip()
    return {a: t for a, t in blocks.items() if t}


def apply(prose_path: Path, world_path: Path) -> None:
    world = json.loads(world_path.read_text(encoding="utf-8"))
    blocks = parse_prose(prose_path)
    changed = 0
    for address, text in blocks.items():
        try:
            before = read_at(world, address)
        except (KeyError, IndexError, StopIteration):
            raise SystemExit(f"{prose_path}: '{address}' does not exist in {world_path}. "
                             "Re-run extract, or fix the heading.")
        if before != text:
            write_at(world, address, text)
            changed += 1

    serialized = json.dumps(world, indent=2, ensure_ascii=False) + "\n"
    scratch = world_path.with_suffix(".json.checking")
    scratch.write_text(serialized, encoding="utf-8")
    try:
        load_world(scratch)
    except WorldValidationError as exc:
        raise SystemExit(f"Not written — the edited world is not valid: {exc}")
    finally:
        scratch.unlink(missing_ok=True)

    world_path.write_text(serialized, encoding="utf-8")
    print(f"{world_path}: {changed} block(s) updated from {prose_path}"
          if changed else f"{world_path}: already up to date")

    # Written, but said out loud: a mistyped pronoun token is valid JSON and valid
    # prose, so nothing above catches it. This is the tightest loop it can be
    # caught in — the author is still looking at the sentence they just wrote.
    mistyped = [(address, token) for address, text in blocks.items()
                for token in unknown_tokens(text)]
    for address, token in mistyped:
        print(f"  warning: {address} contains {token}, which is not a pronoun token. "
              "The player will see the braces.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("extract").add_argument("world", type=Path)
    sub.add_parser("apply").add_argument("prose", type=Path)
    args = parser.parse_args()

    if args.command == "extract":
        extract(args.world, args.world.with_suffix(".prose.md"))
    else:
        name = args.prose.name.removesuffix(".prose.md")
        apply(args.prose, args.prose.with_name(name + ".json"))


if __name__ == "__main__":
    main()
